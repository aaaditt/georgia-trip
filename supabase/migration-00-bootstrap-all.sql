  SELECT 1 AS ord, 'tables present' AS check,
         '18 of 18' AS expected,
         (18 - (SELECT n FROM missing_tables))::text || ' of 18'
           || COALESCE(' (missing: ' || (SELECT names FROM missing_tables) || ')', '') AS actual,
         CASE WHEN (SELECT n FROM missing_tables) = 0 THEN 'OK' ELSE 'FAIL' END AS status
  UNION ALL
  SELECT 2, 'RLS enabled on every table', 'all',
         CASE WHEN (SELECT n FROM rls_off) = 0 THEN 'all'
              ELSE 'RLS OFF on: ' || (SELECT names FROM rls_off) END,
         CASE WHEN (SELECT n FROM rls_off) = 0 THEN 'OK' ELSE 'FAIL' END
  UNION ALL
  SELECT 3, 'public RPCs', '28', (SELECT pub FROM funcs)::text,
         CASE WHEN (SELECT pub FROM funcs) = 28 THEN 'OK' ELSE 'FAIL' END
  UNION ALL
  SELECT 4, 'private helper functions', '3', (SELECT priv FROM funcs)::text,
         CASE WHEN (SELECT priv FROM funcs) = 3 THEN 'OK' ELSE 'FAIL' END
  UNION ALL
  SELECT 5, 'all of them SECURITY DEFINER', '0 plain',
         (SELECT not_secdef FROM funcs)::text || ' plain',
         CASE WHEN (SELECT not_secdef FROM funcs) = 0 THEN 'OK' ELSE 'FAIL' END
  UNION ALL
  SELECT 6, 'realtime publication', '>= 9 tables',
         (SELECT count(*)::text FROM pg_publication_tables WHERE pubname = 'supabase_realtime'),
         CASE WHEN (SELECT count(*) FROM pg_publication_tables
