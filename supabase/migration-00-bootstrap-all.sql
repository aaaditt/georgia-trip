-- ============================================================================
-- migration-00-bootstrap-all.sql
-- Georgia Trip Planner - COMPLETE database bootstrap, safe to run ONCE on a
-- database in ANY state: empty, partially migrated, or fully up to date.
--
-- WHY THIS FILE EXISTS
--   The project's history is schema.sql followed by migration-01..09, each
--   meant to be run in order. If you don't know which ones ran (or you ran
--   them out of order and hit "relation ... does not exist"), running them
--   one at a time is guesswork. This file is all ten, in the correct order,
--   in one paste.
--
-- HOW TO RUN
--   Supabase Dashboard > SQL Editor > New query > paste this whole file >
--   Run. It executes as a single transaction: if anything fails, NOTHING is
--   applied and you are left exactly where you started. Re-running it after
--   a success is a no-op.
--
-- WHAT IT DOES NOT DO
--   It never drops a table, never deletes a row, and never truncates. The
--   only DROPs are `DROP POLICY IF EXISTS` and `DROP CONSTRAINT IF EXISTS`
--   immediately followed by the CREATE/ADD that replaces them - that is the
--   idempotency mechanism, not data loss. Existing data is preserved.
--
-- HOW IT WAS BUILT
--   Generated by concatenating, in order:
--     schema.sql, migration-01 .. migration-09
--   with exactly two mechanical changes, each marked inline with the comment
--   `-- bootstrap: guarded`:
--     * T1 unguarded `ALTER PUBLICATION ... ADD TABLE x` statements wrapped
--       in a DO block trapping duplicate_object (ADD TABLE has no IF NOT
--       EXISTS form, so a second run would otherwise abort).
--     * T2 unguarded `CREATE POLICY` statements preceded by
--       `DROP POLICY IF EXISTS` (CREATE POLICY has no OR REPLACE).
--   Nothing else was edited, reordered, or removed. Migrations 05-09 were
--   already fully idempotent and are byte-identical to their source files.
--
-- A NOTE ON THE LEGACY SEED DATA
--   schema.sql and migration-02 insert the original single-trip data (8
--   users, 8 regions, ~57 experiences) with no trip_id. After migration-06
--   the app scopes every read by trip_id, so these rows are invisible to it
--   - harmless history, not live content. They do NOT collide with the
--   Georgia catalog: migration-09 seeds per-trip rows with ids of the form
--   `<slug>-<trip_uuid>`, a different key space entirely.
--
-- AFTER RUNNING
--   Run the verification block at the very bottom of this file.
-- ============================================================================



