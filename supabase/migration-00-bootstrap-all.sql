WITH expected_tables(t) AS (
  VALUES ('users'),('regions'),('experiences'),('votes'),('ratings'),('comments'),
         ('itinerary_items'),('calendar_access'),('place_notes'),('trip_notes'),
         ('profiles'),('trips'),('trip_members'),('trip_invites'),
         ('comment_reports'),('blocked_members'),('catalog_regions'),('catalog_places')
),
missing_tables AS (
  SELECT string_agg(t, ', ' ORDER BY t) AS names, count(*) AS n
  FROM expected_tables e
  WHERE NOT EXISTS (
    SELECT 1 FROM pg_tables p WHERE p.schemaname = 'public' AND p.tablename = e.t
  )
),
rls_off AS (
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname) AS names, count(*) AS n
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN expected_tables e ON e.t = c.relname
  WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity
),
funcs AS (
  SELECT
    count(*) FILTER (WHERE n.nspname = 'public')  AS pub,
    count(*) FILTER (WHERE n.nspname = 'private') AS priv,
    count(*) FILTER (WHERE NOT p.prosecdef)       AS not_secdef
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname IN ('public', 'private')
    AND p.prokind = 'f'
    AND p.proname IN (
      'handle_new_auth_user','handle_new_trip','redeem_trip_invite','delete_own_account',
      'create_trip','update_own_profile','add_region','add_experience','upsert_vote',
      'upsert_rating','add_comment','delete_comment','add_itinerary_item',
