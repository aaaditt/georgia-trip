      'revoke_calendar_access','upsert_place_note','upsert_trip_note','update_member_role',
      'remove_trip_member','report_comment','dismiss_report','block_member','unblock_member',
      'seed_trip_catalog','create_georgia_trip','set_trip_region_selected',
      'is_trip_member','is_trip_admin','my_member_ids'
    )
)
